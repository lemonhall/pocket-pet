"""Draw the room and the cat. Sprites come from assets/siamese.png (a derivative
of the LPC cat sheet, CC-BY 3.0 - see assets/CREDITS.md).

The sheet is 4 columns x 5 rows of 32x32 frames, generated by tools/make_siamese.py:
  row 0: walk right (0,1,2) + sleep (3)
  row 1: back view (0,1,2)
  row 2: front view (0,1,2)
  row 3: walk left (0,1,2) + sleep (3)
  row 4: head down / eat-groom (0..3)
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw

from . import world

ROOT = Path(__file__).resolve().parents[1]
SHEET = ROOT / "assets" / "siamese.png"
F = 32
SCALE = 4                      # the room is rendered at 4x for a readable GIF

ROW = {"right": 0, "up": 1, "down": 2, "left": 3}

# The firmware pre-renders these as bitmaps (it has no font code), so the order
# here is an interface: display_cat.c indexes cat_label_off[] with it.
GOAL_LABELS = ("seek_food", "sleep", "play", "groom", "follow_owner", "scratch", "explore", "hide")
DRIVE_LABELS = ("hunger", "energy", "bored", "clingy", "litter", "curiosity", "bold", "lazy", "scruff")


def load_sheet() -> Image.Image:
    if not SHEET.exists():
        raise FileNotFoundError(f"{SHEET} is missing - run tools/make_siamese.py")
    return Image.open(SHEET).convert("RGBA")


def cat_frame(sheet: Image.Image, cat: world.Cat, t: int) -> Image.Image:
    """Pick the sprite cell for the cat's current state."""
    if cat.asleep:
        col = 3
        row = ROW["right"]
    elif cat.moving:
        col = t % 3
        row = ROW[cat.facing()]
    elif cat.last in ("groom", "seek_food") and not cat.moving:
        col = min(3, t % 4)
        row = 4
    else:
        col = 0
        row = ROW[cat.facing()]
    return sheet.crop((col * F, row * F, col * F + F, row * F + F))


def draw_room(d: ImageDraw.ImageDraw) -> None:
    d.rectangle([0, 0, world.W, world.H], fill=world.FLOOR)
    for i in range(0, world.W, 16):                    # a hint of floorboards
        d.line([(i, world.WALL_H), (i, world.H)], fill=world.FLOOR_ALT)
    d.rectangle([0, 0, world.W, world.WALL_H], fill=world.WALL)
    d.rectangle([0, 0, world.W, 4], fill=world.WALL_DARK)
    x, y = world.ANCHORS["window"]
    d.rectangle([x - 22, y - 10, x + 22, y + 8], fill=world.WINDOW_FRAME)
    d.rectangle([x - 19, y - 7, x + 19, y + 5], fill=world.WINDOW)
    # the cat tree
    tx, ty = world.ANCHORS["tree"]
    d.rectangle([tx - 10, ty - 12, tx + 10, ty + 22], fill=world.TREE)
    d.rectangle([tx - 16, ty - 16, tx + 16, ty - 6], fill=world.WALL_DARK)
    # the food bowl and the litter box
    fx, fy = world.ANCHORS["food"]
    d.ellipse([fx - 9, fy - 5, fx + 9, fy + 5], fill=world.BOWL)
    d.ellipse([fx - 6, fy - 2, fx + 6, fy + 2], fill=(240, 226, 198))
    lx, ly = world.ANCHORS["litter_box"]
    d.rectangle([lx - 16, ly - 10, lx + 16, ly + 10], fill=world.LITTER)
    d.rectangle([lx - 13, ly - 7, lx + 13, ly + 7], fill=(206, 198, 184))
    # the toy
    ox, oy = world.ANCHORS["toy"]
    d.ellipse([ox - 4, oy - 4, ox + 4, oy + 4], fill=world.TOY)


def render(cat: world.Cat, t: int, sheet: Image.Image) -> Image.Image:
    img = Image.new("RGBA", (world.W, world.H), (0, 0, 0, 255))
    d = ImageDraw.Draw(img)
    draw_room(d)
    frame = cat_frame(sheet, cat, t)
    img.alpha_composite(frame, (int(cat.x) - F // 2, int(cat.y) - F // 2))
    return img.resize((world.W * SCALE, world.H * SCALE), Image.NEAREST)
